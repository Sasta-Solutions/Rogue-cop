"""Pack every audio/*.mp3 into audio/bank.js so the game works from a double-clicked index.html
(browsers block fetching files from file://, but a <script> is allowed).

    python tools/build_bank.py

Names: shot_player_1.mp3, shot_player_2.mp3 ... become variants of "shot_player" (a random one plays
each time). Any name here replaces the built-in synthesized sound of the same name in audio/synth.js.
With no mp3 files, bank.js is empty and the game uses the synthesized set."""
import base64, glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = sorted(glob.glob(os.path.join(ROOT, 'audio', '*.mp3')))
bank = {os.path.basename(f)[:-4]: base64.b64encode(open(f, 'rb').read()).decode() for f in files}
with open(os.path.join(ROOT, 'audio', 'bank.js'), 'w', encoding='utf-8') as out:
    out.write('/* generated by tools/build_bank.py - recorded sounds, base64 mp3 */\nwindow.HOT_ENTRY_AUDIO=')
    out.write(json.dumps(bank, separators=(',', ':')) if bank else 'null')
    out.write(';\n')
print(len(bank), 'sounds,', round(os.path.getsize(os.path.join(ROOT, 'audio', 'bank.js')) / 1e6, 2), 'MB')
